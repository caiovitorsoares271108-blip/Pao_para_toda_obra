CREATE VIEW v_sales_by_day WITH (security_invoker = true) AS
SELECT (created_at AT TIME ZONE 'America/Sao_Paulo')::date AS day,
       COUNT(*) AS orders, SUM(total) AS revenue
  FROM orders
 WHERE status <> 'cancelado'
 GROUP BY 1
 ORDER BY 1 DESC;

CREATE VIEW v_top_products WITH (security_invoker = true) AS
SELECT i.product_id, i.name, SUM(i.quantity) AS units_sold,
       SUM(i.quantity * i.price) AS revenue
  FROM order_items i
  JOIN orders o ON o.id = i.order_id AND o.status <> 'cancelado'
 GROUP BY i.product_id, i.name
 ORDER BY units_sold DESC;

