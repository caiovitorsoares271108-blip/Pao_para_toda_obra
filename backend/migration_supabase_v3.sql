CREATE OR REPLACE FUNCTION guard_order_items() RETURNS trigger AS $$
DECLARE st VARCHAR(30);
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT status INTO st FROM orders WHERE id = NEW.order_id;
    IF st IS DISTINCT FROM 'pendente' THEN
      RAISE EXCEPTION 'Só é possível adicionar itens a pedido pendente (status: %)', COALESCE(st, 'inexistente')
        USING ERRCODE = '23514';
    END IF;
  ELSIF NEW.order_id <> OLD.order_id OR NEW.product_id <> OLD.product_id
     OR NEW.quantity <> OLD.quantity OR NEW.price <> OLD.price THEN
    RAISE EXCEPTION 'Itens de pedido são imutáveis: cancele e refaça o pedido'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

