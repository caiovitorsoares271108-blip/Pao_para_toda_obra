CREATE OR REPLACE FUNCTION guard_order_status() RETURNS trigger AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status
     AND NOT EXISTS (
       SELECT 1 FROM order_status_transitions
        WHERE from_status = OLD.status AND to_status = NEW.status
     ) THEN
    RAISE EXCEPTION 'Transição de status inválida: % -> % (pedido %)', OLD.status, NEW.status, OLD.id
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

